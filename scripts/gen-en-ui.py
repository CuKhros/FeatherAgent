import json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'scripts' / 'en-ui'))
from tui_en import EN as TUI_EN
from kernel_en import EN as KERNEL_EN
from app_en import EN as APP_FULL
from app_extra import EXTRA as APP_EXTRA
from web_en import INDEX_EN, WEBUI_EN
from index_en import LINES as INDEX_LINES


def rust_lit(s):
    return json.dumps(s, ensure_ascii=False)[1:-1]

def zh_lits(src):
    vals = re.findall(r'"((?:[^"\\]|\\.)*)"', src)
    return sorted({x for x in vals if re.search('[\u4e00-\u9fff]', x)})

def gen_rust(src_path, out_path, ens, rename=None):
    src = src_path.read_text(encoding='utf-8')
    if '#[cfg(test)]' in src:
        src = src[:src.index('#[cfg(test)]')].rstrip() + '\n'
    zh = zh_lits(src)
    assert len(zh) == len(ens), (src_path, len(zh), len(ens))
    pairs = sorted(zip(zh, ens), key=lambda p: -len(p[0]))
    for z, e in pairs:
        src = src.replace('"' + z + '"', '"' + rust_lit(e) + '"')
    if rename:
        for a, b in rename:
            src = src.replace(a, b)
    left = [x for x in zh_lits(src)]
    assert not left, (src_path, left[:5])
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        '//! English UI variant generated from %s; do not edit directly.\n'
        '//! Regenerate: python3 scripts/gen-en-ui.py\n\n%s' % (src_path.name, src),
        encoding='utf-8',
    )
    print('generated', out_path)

def gen_web():
    src = (ROOT / 'web/app.js').read_text(encoding='utf-8')
    vals = []
    for pat in [r'"((?:[^"\\]|\\.)*)"', r"'((?:[^'\\]|\\.)*)'", r'`((?:[^`\\]|\\.)*)`']:
        vals += re.findall(pat, src, re.S)
    zh = sorted({x for x in vals if re.search('[\u4e00-\u9fff]', x)})
    full = dict(zip(json.loads((ROOT/'scripts/en-ui-app.json').read_text()), APP_FULL))
    body = (ROOT / 'scripts' / 'en-ui' / 'i18n_old.rs').read_text(encoding='utf-8')
    body = body[body.index('const PHRASES'):body.index('];', body.index('const PHRASES'))]
    phr = re.findall(r'\("((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\)', body)
    pending = []
    for x in zh:
        if x in full:
            continue
        y = x
        for a, b in phr:
            y = y.replace(a, b)
        if re.search('[\u4e00-\u9fff]', y):
            pending.append(x)
        else:
            full[x] = y
    assert len(pending) == len(APP_EXTRA), (len(pending), len(APP_EXTRA))
    full.update(dict(zip(pending, APP_EXTRA)))
    for z in sorted(full, key=len, reverse=True):
        src = src.replace(z, full[z])
    out = ROOT / 'web/app.en.js'
    out.write_text('// English UI asset generated by scripts/gen-en-ui.py; do not edit directly.\n' + src, encoding='utf-8')
    vals = []
    for pat in [r'"((?:[^"\\]|\\.)*)"', r"'((?:[^'\\]|\\.)*)'", r'`((?:[^`\\]|\\.)*)`']:
        vals += re.findall(pat, src, re.S)
    left = sorted({x for x in vals if re.search('[\u4e00-\u9fff]', x)})
    assert not left, left[:5]
    print('generated', out)

    html = (ROOT/'web/index.html').read_text(encoding='utf-8').splitlines(keepends=True)
    for n, line in INDEX_LINES.items():
        old = html[n-1]
        indent = old[:len(old)-len(old.lstrip())]
        nl = '\n' if old.endswith('\n') else ''
        html[n-1] = indent + line + nl
    text = ''.join(html).replace('web/app.js', 'web/app.en.js').replace('lang="zh-CN"', 'lang="en"')
    out = ROOT / 'web/index.en.html'
    out.write_text(text, encoding='utf-8')
    assert not [l for l in text.splitlines() if re.search('[\u4e00-\u9fff]', l) and '<!--' not in l], 'index english leftover'
    print('generated', out)

def main():
    gen_rust(ROOT/'src/bin/tui.rs', ROOT/'src/bin/tui_en.rs', TUI_EN,
             rename=[('Usage: featheragent-tui', 'Usage: featheragent-tui-en'),
                     ('featheragent serve', 'featheragent-en serve')])
    gen_rust(ROOT/'src/bin/kernel.rs', ROOT/'src/bin/kernel_en.rs', KERNEL_EN,
             rename=[('Usage: featheragent <', 'Usage: featheragent-en <'),
                     ('featheragent serve', 'featheragent-en serve'),
                     ('"featheragent-webui.exe"', '"featheragent-webui-en.exe"'),
                     ('"featheragent-webui"', '"featheragent-webui-en"'),
                     ('launch featheragent-webui[.exe]', 'launch featheragent-webui-en[.exe]'),
                     ('featheragent-webui not found;', 'featheragent-webui-en not found;')])
    gen_web()

if __name__ == '__main__':
    main()
    import subprocess
    subprocess.run(['cargo', 'fmt', '--all'], check=True)
